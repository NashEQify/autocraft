// A follow-up table made before it was keyed by source (the release that added it) migrates to the table a new database has,
// and keeps its rows as the pre-merge review's. Runs on SQLite, and on Postgres under `pnpm test:pg`.
import assert from "node:assert/strict";
import { test } from "node:test";
import type { Db } from "./helpers/raw-db.ts";
import { testDatabase } from "./test-db.ts";

const OLD = {
  sqlite: `CREATE TABLE premerge_followups (repo TEXT NOT NULL, number INTEGER NOT NULL, head_oid TEXT NOT NULL, issue_number INTEGER, url TEXT,
    state TEXT NOT NULL, at TEXT NOT NULL, note TEXT, PRIMARY KEY (repo, number, head_oid))`,
  postgres: `CREATE TABLE premerge_followups (repo text COLLATE "C" NOT NULL, number bigint NOT NULL, head_oid text COLLATE "C" NOT NULL, issue_number bigint,
    url text COLLATE "C", state text COLLATE "C" NOT NULL, at text COLLATE "C" NOT NULL, note text COLLATE "C", rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    PRIMARY KEY (repo, number, head_oid))`,
};

/** The table as the database has it: its definition (SQLite), or its columns, indexes and triggers (Postgres). */
async function shape(db: Db): Promise<string[]> {
  const q = db.dialect === "sqlite"
    ? "SELECT sql AS o FROM sqlite_master WHERE tbl_name = 'premerge_followups' AND sql IS NOT NULL"
    : `SELECT column_name || ' ' || data_type || ' ' || is_nullable || ' ' || ordinal_position AS o FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'premerge_followups'
       UNION ALL SELECT indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = 'premerge_followups'
       UNION ALL SELECT tgname::text FROM pg_trigger WHERE tgrelid = to_regclass('premerge_followups') AND NOT tgisinternal`;
  return (await db.prepare(q).all()).map((r) => String(r.o)).sort();
}

test("a follow-up table without a source migrates to a new database's table and keeps its rows as the pre-merge review's", async () => {
  const t = await testDatabase("", undefined, { empty: true });
  const fresh = await testDatabase("", undefined, { empty: true });
  try {
    const db = await t.open({ app: true });
    await db.script(`DROP TABLE premerge_followups; ${OLD[db.dialect]};
      INSERT INTO premerge_followups (repo, number, head_oid, issue_number, url, state, at, note) VALUES ('app', 1, 'sha1', 7, 'https://github.com/o/app/issues/7', 'filed', 'a', NULL);
      UPDATE settings SET value = 'before' WHERE key = 'schema_stamp'`);
    const again = await t.open({ app: true });
    assert.deepEqual((await again.prepare("SELECT source, head_oid, issue_number FROM main.premerge_followups").all()).map((r) => ({ ...r, issue_number: Number(r.issue_number) })),
      [{ source: "premerge", head_oid: "sha1", issue_number: 7 }]);
    assert.deepEqual(await shape(again), await shape(await fresh.open({ app: true })));
    // A review row of the same head is a row of its own.
    await again.prepare("INSERT INTO main.premerge_followups (repo, number, source, head_oid, state, at) VALUES ('app', 1, 'review', 'sha1', 'filing', 'b')").run();
  } finally {
    await t.close();
    await fresh.close();
  }
});
